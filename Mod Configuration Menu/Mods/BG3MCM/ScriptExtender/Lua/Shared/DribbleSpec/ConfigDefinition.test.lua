local StorageSyncService = Ext.Require("Shared/DynamicSettings/Services/StorageSyncService.lua")
local JsonAdapter = Ext.Require("Shared/DynamicSettings/Adapters/JsonAdapter.lua")
local SettingsService = Ext.Require("Shared/DynamicSettings/Services/SettingsService.lua")
local NewSandbox = Ext.Require("Shared/DribbleSpec/Fixtures/Sandbox.lua")

D.describe("Config definition fixtures", { tags = { "config-definition", "unit" } }, function()
    local sandbox = NewSandbox(StorageSyncService, JsonAdapter, SettingsService)
    local invalidations
    D.beforeEach(function(ctx)
        sandbox:Isolate(ctx)
        invalidations = 0
        ctx.stub(BlueprintShape, "InvalidateCache", function() invalidations = invalidations + 1 end)
        ctx.stub(BlueprintCache, "GetOrBuild", function(_, root, build) return build(root) end)
    end)
    D.afterEach(function() sandbox:Restore() end)

    D.test("constructs nested definitions and stamps ownership", function()
        local blueprint = Blueprint:New({ ModUUID = "fixture", SchemaVersion = 2, Optional = true,
            ModName = "Fixture", ModDescription = "Description", HiddenFromList = true, ListFolder = "Folder",
            Settings = { { Id = "root", Type = "enum", Default = "a" } },
            Tabs = { { TabId = "tab", TabName = "Tab", Settings = { { Id = "nested", Default = false } },
                Sections = { { SectionId = "section", SectionName = "Section", Settings = { { Id = "leaf", Default = 4 } } } } } } })
        D.expect(blueprint:GetModUUID()).toBe("fixture")
        D.expect(blueprint:GetSchemaVersion()).toBe(2)
        D.expect(blueprint:GetOptional()).toBe(true)
        D.expect(blueprint:GetHiddenFromList()).toBe(true)
        D.expect(blueprint:GetListFolder()).toBe("Folder")
        D.expect(blueprint:GetModName()).toBe("Fixture")
        D.expect(blueprint:GetModDescription()).toBe("Description")
        D.expect(blueprint:GetTabs()[1]:GetId()).toBe("tab")
        D.expect(blueprint:GetTabs()[1]:GetSections()[1]:GetId()).toBe("section")
        D.expect(blueprint:GetSettingById("leaf"):GetModUUID()).toBe("fixture")
        D.expect(blueprint:RetrieveDefaultValueForSetting("nested")).toBe(false)
        D.expect(#blueprint:GetAllSettingsOrdered()).toBe(3)
        D.expect(blueprint:GetDefaultSettingsFromBlueprint(blueprint).leaf).toBe(4)
    end)

    D.test("setting preserves fields and copies table defaults", function()
        local setting = BlueprintSetting:New({ Id = "id", OldId = "old", Name = "Name", Type = "list_v2", Default = { "x" }, Description = "desc", Tooltip = "tip", VisibleIf = "condition", Options = { SortOrder = 3 } })
        D.expect(setting:GetId()).toBe("id")
        D.expect(setting:GetOldId()).toBe("old")
        D.expect(setting:GetLocaName()).toBe("Name")
        D.expect(setting:GetType()).toBe("list_v2")
        D.expect(setting:GetVisibleIf()).toBe("condition")
        D.expect(setting:GetDescription()).toBe("desc")
        D.expect(setting:GetTooltip()).toBe("tip")
        D.expect(setting:GetSortOrder()).toBe(3)
        local copy = setting:GetDefault(); copy[1] = "changed"
        D.expect(setting:GetDefault()[1]).toBe("x")
        setting:SetId("new"); setting:SetName("New"); setting:SetType("text"); setting:SetDefault(false)
        setting:SetDescription("D"); setting:SetTooltip("T"); setting:SetSection("S"); setting:SetSortOrder(8)
        D.expect(setting:GetId()).toBe("new")
        D.expect(setting:GetName()).toBe("New")
        D.expect(setting:GetType()).toBe("text")
        D.expect(setting:GetDefault()).toBe(false)
        D.expect(setting:GetDescription()).toBe("D")
        D.expect(setting:GetTooltip()).toBe("T")
        D.expect(setting:GetSection()).toBe("S")
        D.expect(setting:GetSortOrder()).toBe(8)
    end)

    D.test("adds isolated settings and sections", function()
        local blueprint = Blueprint:New({ ModUUID = "fixture" })
        local added = blueprint:AddSection("Added", "Added description")
        D.expect(added:GetLocaName()).toBe("Added")
        D.expect(added:GetDescription()).toBe("Added description")
        blueprint:AddSetting({ Id = "root" })
        D.expect(blueprint:GetSettings()[1]:GetModUUID()).toBe("fixture")
        local tab = BlueprintTab:New({ TabName = "Tab", TabDescription = "Description" })
        tab:AddSetting({ Id = "tab-setting" }):AddSection({ SectionId = "s", SectionName = "Section" })
        D.expect(tab:GetTabName()).toBe("Tab")
        D.expect(tab:GetTabDescription()).toBe("Description")
        D.expect(tab:GetSettings()[1]:GetId()).toBe("tab-setting")
        local section = tab:GetSections()[1]
        section:AddSetting("Name", "text", "default", "description")
        D.expect(section:GetLocaName()).toBe("Section")
        D.expect(section:GetSettings()[1]:GetDefault()).toBe("default")
        D.expect(#tab:GetAllSettings()).toBe(2)
    end)

    D.test("invalidates the shape after changing definition structure or an id", function()
        local blueprint = Blueprint:New({ ModUUID = "fixture" })
        local tab = BlueprintTab:New({})
        local section = BlueprintSection:New({})
        local setting = BlueprintSetting:New({ Id = "before" })
        D.expect(invalidations).toBe(0)
        blueprint:SetTabs({ tab })
        blueprint:SetSections({ section })
        blueprint:SetSettings({ setting })
        blueprint:AddSection("Section", "Description")
        blueprint:AddSetting({ Id = "root" })
        tab:AddSection({ SectionName = "Nested" })
        tab:AddSetting({ Id = "nested" })
        section:AddSetting("Name", "text", "value", "Description")
        setting:SetId("after")
        D.expect(invalidations).toBe(9)
    end)

    D.test("preserves optional fields and independent nested definitions", function()
        local tab = BlueprintTab:New({ TabId = "outer", VisibleIf = "tab-condition",
            Tabs = { { TabId = "inner" } }, Handles = { marker = "tab" } })
        local section = BlueprintSection:New({ SectionId = "section", VisibleIf = "section-condition",
            Options = { marker = "options" }, Tabs = { { TabId = "child" } }, Handles = { marker = "section" } })
        D.expect(tab:GetVisibleIf()).toBe("tab-condition")
        D.expect(tab:GetTabs()[1]:GetId()).toBe("inner")
        D.expect(tab:GetHandles().marker).toBe("tab")
        tab:SetHandles({ marker = "new" })
        D.expect(tab:GetHandles().marker).toBe("new")
        D.expect(section:GetVisibleIf()).toBe("section-condition")
        D.expect(section:GetOptions().marker).toBe("options")
        D.expect(section:GetHandles().marker).toBe("section")
        D.expect(section:GetTabs()[1]:GetId()).toBe("child")
        section:SetSectionName("Renamed")
        section:SetSectionDescription("Updated")
        D.expect(section:GetLocaName()).toBe("Renamed")
        D.expect(section:GetDescription()).toBe("Updated")
        local other = BlueprintSection:New({})
        D.expect(#other:GetTabs()).toBe(0)
        D.expect(#other:GetSettings()).toBe(0)
    end)
end)
